/**
 * 間隔重複的排程。
 *
 * 用 Leitner 盒子，不用 SM-2。
 * SM-2 需要使用者自評 0–5 的熟悉度，而這個網站的作答結果只有對與錯兩種——
 * 硬把二元結果塞進五級量表，排出來的間隔看起來科學但其實是憑空捏造的。
 * Leitner 天生就吃二元評分：答對往上一盒、答錯打回第一盒。
 *
 * 時間一律由呼叫端傳進來，這裡不自己取。理由與亂數相同：
 * 測試要能在固定的時間點上重現同一份排程。
 */

/**
 * 各盒的間隔天數。
 * 第一盒的一天是刻意的——答錯的東西隔天就該再看到，
 * 但不是同一局立刻再考一次（那只是短期記憶，不會留下來）。
 */
export const BOX_DAYS = [1, 3, 7, 16, 35];

/**
 * 最高盒號。到頂之後就停在最長的間隔，不再往上加
 */
export const MAX_BOX = BOX_DAYS.length;

/**
 * 到這一盒就算學會了，不再列進「易錯」。
 *
 * 第 4 盒代表上次答錯之後又連續答對三次（1→2→3→4）。
 * 沒有這條線的話「易錯」永遠不會縮小——錯誤次數只增不減，
 * 一個字錯過一次就會跟著你一輩子，那份清單會失去它唯一的價值（很短）。
 * 再錯一次就打回第一盒，它自己會回到清單裡。
 */
export const GRADUATED_BOX = 4;

/**
 * 這筆記錄算不算已經學會
 */
export function isGraduated(record) {
  return Number(record?.box) >= GRADUATED_BOX;
}

/**
 * 盒號一律夾在 1..MAX_BOX。
 * 資料是使用者可以匯入的，不能假設它一定在範圍內
 */
const clampBox = (box) => {
  if (!Number.isInteger(box) || box < 1) return 1;
  return Math.min(box, MAX_BOX);
};

/**
 * 這次作答之後該進哪一盒。
 * 答錯一律回到第一盒，不是退一盒——記錯的東西要當成沒學過重新來，
 * 只退一格會讓一個一直記錯的字在高盒之間反覆橫跳，永遠排不到該有的密度。
 */
export function nextBox(box, correct) {
  return correct ? Math.min(clampBox(box) + 1, MAX_BOX) : 1;
}

/**
 * 兩次見到同一題之間至少要隔這麼久。
 *
 * 只對齊日界不夠：23:50 答錯的題目排到「隔天 00:00」等於十分鐘後，
 * 使用者按一下「再玩一局」就又看到它，而上面那條
 * 「答錯的東西隔天再看到，但不是同一局立刻再考一次」正好被自己違反。
 *
 * 所以兩條規則各管一邊：日界負責「別把早上練習的人推遲一天」，
 * 這條地板負責「別在同一個晚上又見面」。
 *
 * 六小時足以跨過一次練習與一夜睡眠，又不會把晚上答錯的題目推到隔天下午。
 * 只有第一盒的深夜情境會踩到它——第二盒起的間隔至少三天，永遠比它遠。
 */
const MIN_GAP_MS = 6 * 3600000;

/**
 * 在某一盒的話，下次該在什麼時候出現。
 *
 * 對齊到當地時間的日界，不是「從現在起算 N 個 24 小時」。
 *
 * 直接加毫秒的話，晚上 22:00 答錯的題目要到隔天 22:00 才算到期——
 * 習慣早上練的人一整個上午都看不到它，等於被系統性推遲一天，
 * 而且他每天練習的時間只要早一點點，這個延遲就會一直累積下去。
 * 間隔重複的單位本來就是「天」而不是「小時」，落在哪一天才是重點。
 *
 * 但對齊之後還要過 MIN_GAP_MS 那道地板，理由見上面。
 */
export function dueAfter(box, now) {
  const at = new Date(now);
  /* 先退到今天的開始，再往前推 N 天，結果落在某一天的 00:00 */
  at.setHours(0, 0, 0, 0);
  at.setDate(at.getDate() + BOX_DAYS[clampBox(box) - 1]);
  return Math.max(at.getTime(), now + MIN_GAP_MS);
}

/**
 * 這筆記錄到期了沒。沒有 due 的一律視為到期——
 * 那表示它來自更早的資料格式，讓它出現一次重新排程，比永遠不出現好。
 */
export function isDue(record, now) {
  const due = record?.due;
  return !Number.isFinite(due) || due <= now;
}
