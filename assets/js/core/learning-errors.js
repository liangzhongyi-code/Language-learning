/**
 * details 僅放結構化診斷，不放完整備份、答案、憑證或原始私人資料。
 */
export class LearningError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = 'LearningError';
    this.code = code;
    this.details = details;
  }
}
